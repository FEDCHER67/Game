def khrush(x0, y0, x1, y1, arches=()):
    rect(x0 + 1.2, y0 + 1.6, x1 + 1.2, y1 + 1.6, (60, 64, 66, 70))                   # тень
    rect(x0, y0, x1, y1, GREY, GREY_OUT, 2)
    horiz = (x1 - x0) > (y1 - y0)
    L = (x1 - x0) if horiz else (y1 - y0)
    n = max(2, int(L / 14))
    for k in range(n):                                                                # выходы на крышу (по подъездам)
        t = (k + 0.5) / n
        if horiz:
            cx, cy = x0 + (x1 - x0) * t, (y0 + y1) / 2
        else:
            cx, cy = (x0 + x1) / 2, y0 + (y1 - y0) * t
        rect(cx - 1.4, cy - 1.4, cx + 1.4, cy + 1.4, (128, 130, 130), GREY_OUT)
    for a0, a1 in arches:                                                             # арка под домом
        if horiz:
            rect(a0, y0, a1, y1, (190, 188, 180))
            line([(a0, y0), (a0, y1)], GREY_OUT, 0.5)
            line([(a1, y0), (a1, y1)], GREY_OUT, 0.5)
        else:
            rect(x0, a0, x1, a1, (190, 188, 180))
            line([(x0, a0), (x1, a0)], GREY_OUT, 0.5)
            line([(x0, a1), (x1, a1)], GREY_OUT, 0.5)
    HOUSES.append((x0, y0, x1, y1))


