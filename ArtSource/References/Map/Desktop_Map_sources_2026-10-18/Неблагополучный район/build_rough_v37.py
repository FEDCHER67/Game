"""Неблагополучный район — план v37 (TASK-000601), от v36:
- два верхних дома в центре (сцеплены углами) и гаражи за ними подняты выше (~7 м): между нижним из них и средним домом
  проезд ~12 м для бусика; забор выступа выше;
- гаражи у базы: ряд удлинён на 1 гараж вправо, «ножка» Г из 2 гаражей ушла правее;
- подъезды нарисованы у всех жилых домов: тёмные козырьки на стороне двора, ~через 15 м.
Не перезаписывает. Запуск: python build_rough_v37.py -> Неблагополучный_район_v37.png
"""
import os

from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'Неблагополучный_район_v36.png')
OUT = os.path.join(HERE, 'Неблагополучный_район_v37.png')
if os.path.exists(OUT):
    raise SystemExit(os.path.basename(OUT) + ' exists')

BG, FILL, OUTL = (238, 240, 231), (207, 211, 214), (73, 83, 91)
GAR, GAR_OUT = (180, 202, 204), (100, 120, 128)
FENCE = (112, 119, 119)
DOOR, DOOR_OUT = (96, 106, 116), (50, 58, 66)

img = Image.open(SRC).convert('RGB')
dr = ImageDraw.Draw(img)


def door(side, x, y):
    """Подъезд: козырёк 22×7 px снаружи фасада. side — куда смотрит выход (S/N/E/W), (x, y) — точка на фасаде."""
    if side == 'S':
        dr.rectangle([x - 11, y + 2, x + 11, y + 9], fill=DOOR, outline=DOOR_OUT)
    elif side == 'N':
        dr.rectangle([x - 11, y - 9, x + 11, y - 2], fill=DOOR, outline=DOOR_OUT)
    elif side == 'E':
        dr.rectangle([x + 2, y - 11, x + 9, y + 11], fill=DOOR, outline=DOOR_OUT)
    else:
        dr.rectangle([x - 9, y - 11, x - 2, y + 11], fill=DOOR, outline=DOOR_OUT)


def doors(side, a, b, fixed, n, skip=None):
    for k in range(n):
        t = a + (b - a) * (k + 0.5) / n
        if skip and skip[0] - 15 <= t <= skip[1] + 15:
            continue
        door(side, t, fixed) if side in 'SN' else door(side, fixed, t)


