    n = max(1, int(L / 14))
    for k in range(n):
        t = (k + 0.5) / n
        cx, cy = (x0 + (x1 - x0) * t, (y0 + y1) / 2) if horiz else ((x0 + x1) / 2, y0 + (y1 - y0) * t)
