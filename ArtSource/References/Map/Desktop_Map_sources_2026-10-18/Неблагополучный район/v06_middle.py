# ---------------------------------------------------------------- хрущёвки: все одного серого цвета
GREY, GREY_OUT = (150, 152, 152), (70, 72, 74)
HOUSES = []


def khrush(x0, y0, x1, y1, arches=()):
    rect(x0 + 1.2, y0 + 1.6, x1 + 1.2, y1 + 1.6, (60, 64, 66, 70))
    rect(x0, y0, x1, y1, GREY, GREY_OUT, 2)
    horiz = (x1 - x0) > (y1 - y0)
    L = (x1 - x0) if horiz else (y1 - y0)
    n = max(1, int(L / 14))
    for k in range(n):
        t = (k + 0.5) / n
        cx, cy = (x0 + (x1 - x0) * t, (y0 + y1) / 2) if horiz else ((x0 + x1) / 2, y0 + (y1 - y0) * t)
        rect(cx - 1.4, cy - 1.4, cx + 1.4, cy + 1.4, (128, 130, 130), GREY_OUT)
    for a0, a1 in arches:
        if horiz:
            rect(a0, y0, a1, y1, (190, 188, 180))
            line([(a0, y0), (a0, y1)], GREY_OUT, 0.5)
            line([(a1, y0), (a1, y1)], GREY_OUT, 0.5)
        else:
            rect(x0, a0, x1, a1, (190, 188, 180))
            line([(x0, a0), (x1, a0)], GREY_OUT, 0.5)
            line([(x0, a1), (x1, a1)], GREY_OUT, 0.5)
    HOUSES.append((x0, y0, x1, y1))


def entrances(x0, x1, y, side, n):
    """Подъезды вдоль горизонтального дома: козырёк + лавочка (side=+1 — двор к югу, -1 — к северу)."""
    for k in range(n):
        cx = x0 + (x1 - x0) * (k + 0.5) / n
        rect(cx - 1.2, y, cx + 1.2, y + side * 1.4, (110, 112, 112))
        rect(cx + 1.8, y + side * 2.2, cx + 3.6, y + side * 2.8, (120, 92, 64))


def entrances_v(y0, y1, x, side, n):
    """Подъезды вдоль вертикального дома (side=+1 — двор к востоку, -1 — к западу)."""
    for k in range(n):
        cy = y0 + (y1 - y0) * (k + 0.5) / n
        rect(x, cy - 1.2, x + side * 1.4, cy + 1.2, (110, 112, 112))
        rect(x + side * 2.2, cy + 1.8, x + side * 2.8, cy + 3.6, (120, 92, 64))


def garages(x0, y, n, face, w=3.4, d=6.0, vertical=False):
    """Ряд железных гаражей; face — куда смотрят ворота (N/S для горизонтального ряда, W/E для вертикального)."""
    for k in range(n):
        col = rnd.choice(((122, 98, 82), (96, 112, 124), (112, 120, 100), (130, 110, 92), (104, 104, 108), (140, 90, 70)))
        if not vertical:
            gx = x0 + k * w
            rect(gx, y, gx + w, y + d, col, (60, 60, 60))
            dy = y + d - 0.5 if face == 'S' else y
            rect(gx + 0.4, dy, gx + w - 0.4, dy + 0.5, (50, 52, 54))
        else:
            gy = y + k * w
            rect(x0, gy, x0 + d, gy + w, col, (60, 60, 60))
            dx = x0 + d - 0.5 if face == 'E' else x0
            rect(dx, gy + 0.4, dx + 0.5, gy + w - 0.4, (50, 52, 54))
        if rnd.random() < 0.12:
            if not vertical:
                rect(x0 + k * w + 0.6, y + 1, x0 + k * w + w - 0.6, y + d - 1, (70, 66, 60))


