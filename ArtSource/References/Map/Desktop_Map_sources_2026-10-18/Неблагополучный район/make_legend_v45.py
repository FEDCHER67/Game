A('- **12 Большой двор** (главный центр NPC вместе с 5): большая детская площадка + мусорная секция, турник, будка.')
A('- **10, 11** — арки А1 и А3; **13** — двор у молнии со сквером; **15, 16, 17** — выезды.')
A('')
