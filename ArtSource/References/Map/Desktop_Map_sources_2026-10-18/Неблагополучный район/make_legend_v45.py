A('5. **Лавочки только у подъездов**: у части одна сбоку от дорожки, у части две по бокам, у части нет (число — в JSON `doors[].benches`). Урна у входа на дорожку. Нигде больше лавок не ставить.')
A('6. **Фонари** — вплотную к углам домов (со стороны подъездов), к углам детских площадок и коробки, вдоль внешней дороги на обочине. Ни одного фонаря на колеях-проездах: бусик должен проходить везде.')
A('7. **Деревья** голые, корявые: в палисадниках между подъездами, в двух маленьких скверах, пара за гаражами. Не на колеях и не посреди пустоши без причины.')
A('8. **Ровная земля.** Без холмов и ям.')
