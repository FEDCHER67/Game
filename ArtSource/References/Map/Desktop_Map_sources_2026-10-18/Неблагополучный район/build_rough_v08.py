def pts_inside(pt, pl):
    x, y = pt
    c = False
    for i in range(len(pl)):
        (x0, y0), (x1, y1) = pl[i], pl[(i + 1) % len(pl)]
        if (y0 > y) != (y1 > y) and x < (x1 - x0) * (y - y0) / ((y1 - y0) or 1e-9) + x0:
            c = not c
    return c


